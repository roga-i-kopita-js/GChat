import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import SwaggerParser from '@apidevtools/swagger-parser';
import { createClient } from '@hey-api/openapi-ts';

import { validateSchema } from './validate-schema.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const repository = fileURLToPath(new URL('../../../', import.meta.url));
const input = resolve(process.argv[2] ?? `${root}/openapi.json`);
const output = resolve(process.argv[3] ?? `${root}/src/generated`);
const schemaText = await readFile(input, 'utf8');
const schema = JSON.parse(schemaText);

const operations = validateSchema(schema);

await SwaggerParser.validate(structuredClone(schema), { resolve: { external: false } });
await rm(output, { recursive: true, force: true });
await mkdir(output, { recursive: true });
await createClient({
  input,
  output: { path: output, postProcess: [] },
  plugins: ['@hey-api/typescript'],
});
// The class emitter extends Hey API's operation types with our instance-based public contract.
// It never contains a handwritten endpoint list or duplicates DTO generation.
const typeSource = await readFile(`${output}/types.gen.ts`, 'utf8');
const members = operations.map(
  ({ path, method, operation, parameters, protected: authenticated }) => {
    const id = operation.operationId;
    const prefix = id[0].toUpperCase() + id.slice(1);

    for (const suffix of ['Data', 'Response']) {
      if (!typeSource.includes(`export type ${prefix}${suffix} =`))
        throw new Error(`Missing Hey API type: ${prefix}${suffix}`);
    }

    const sections = [];

    if (operation.requestBody) sections.push('body');

    if (parameters.some((p) => p.in === 'path')) sections.push('path');

    if (parameters.some((p) => p.in === 'query')) sections.push('query');

    const required = operation.requestBody?.required || parameters.some((p) => p.required);
    const descriptor = {
      path,
      method,
      protected: authenticated,
      emptyResponses: Object.entries(operation.responses)
        .filter(([status, response]) => /^2\d\d$/.test(status) && !response.content)
        .map(([status]) => Number(status)),
      parameters: parameters.map(({ name, in: location, style, explode }) => ({
        name,
        in: location,
        ...(style && { style }),
        ...(explode !== undefined && { explode }),
      })),
    };
    const response = `NormalizeVoid<Types.${prefix}Response>`;

    return `
  ${id}(args: Pick<Types.${prefix}Data, ${sections.map((s) => `'${s}'`).join(' | ') || 'never'}> & { signal?: AbortSignal }${required ? '' : ' = {}'}): Promise<ApiResult<${response}>> {
    return this.transport.request<${response}>(${JSON.stringify(descriptor)}, args);
  }`;
  },
);

await writeFile(
  `${output}/backend-api.ts`,
  `// Generated by scripts/generate.mjs using @hey-api/openapi-ts. Do not edit.
import type * as Types from './types.gen.js';
import { ApiTransport } from '../transport.js';
import type { ApiResult, BackendApiOptions } from '../transport.js';

type NormalizeVoid<T> = T extends void ? undefined : T;

export class BackendApi {
  private readonly transport: ApiTransport;

  constructor(options: BackendApiOptions) {
    this.transport = new ApiTransport(options);
  }
${members.join('\n')}
}
`,
);
// Hey API emits extensionless type imports; generated public sources use NodeNext-compatible paths.
await writeFile(
  `${output}/index.ts`,
  "// Generated by scripts/generate.mjs. Do not edit.\nexport type * from './types.gen.js';\nexport { BackendApi } from './backend-api.js';\n",
);
execFileSync(
  'pnpm',
  [
    'exec',
    'oxlint',
    '--config',
    `${repository}/.oxlintrc.json`,
    '--fix',
    '--deny-warnings',
    output,
  ],
  {
    cwd: root,
    stdio: 'pipe',
  },
);
execFileSync(
  'pnpm',
  ['exec', 'prettier', '--config', `${repository}/.prettierrc.json`, '--write', output],
  { cwd: root, stdio: 'pipe' },
);
const backend = `${repository}/applications/backend`;
const sourceFiles = (await readdir(`${backend}/src`, { recursive: true }))
  .filter(
    (file) =>
      file.endsWith('.controller.ts') || file.endsWith('.dto.ts') || file.startsWith('swagger/'),
  )
  .map((file) => `src/${file}`);

sourceFiles.push('nest-cli.json', 'tsconfig.json', 'tsconfig.build.json');
const sourceRevision = createHash('sha256');

for (const file of sourceFiles.sort()) {
  sourceRevision
    .update(file)
    .update('\0')
    .update(await readFile(`${backend}/${file}`))
    .update('\0');
}

await writeFile(
  `${output}/provenance.json`,
  `${JSON.stringify(
    {
      schemaSha256: createHash('sha256').update(schemaText).digest('hex'),
      backendSourceRevisionSha256: sourceRevision.digest('hex'),
    },
    null,
    2,
  )}\n`,
);
console.log(
  `Generated ${operations.length} HTTP operations; schema SHA-256 ${createHash('sha256').update(schemaText).digest('hex')}`,
);
