import { DeviceError } from './contract';

export function deviceErrorMessage(error: unknown): string {
  const code = error instanceof DeviceError ? error.code : '';
  const messages: Record<string, string> = {
    PERMISSION_DENIED: 'Доступ запрещён. Разрешите его в настройках приложения или сайта.',
    RESTRICTED: 'Доступ ограничен системой. Проверьте настройки устройства.',
    UNSUPPORTED: 'Это действие здесь недоступно. Используйте системные настройки устройства.',
    ACCESS_LOST: 'Доступ утрачен. Выберите файл или папку заново.',
    BUSY: 'Сначала завершите звонок или другое действие.',
    CANCELLED: 'Действие отменено.',
    PUSH_UNAVAILABLE: 'Push-уведомления не включены на сервере.',
    NETWORK_ERROR: 'Дождитесь подключения GChat и повторите действие.',
    BRIDGE_UNAVAILABLE: 'Не удалось связаться с приложением. Повторите загрузку.',
    UNAUTHENTICATED: 'Дождитесь восстановления входа в приложение.',
    INTEGRATION_ERROR: 'Версии интерфейса и приложения не согласованы.',
    UNSUPPORTED_VERSION: 'Версии интерфейса и приложения не согласованы.',
    STORAGE_FULL: 'На устройстве недостаточно свободного места.',
    OUTCOME_UNKNOWN: 'Результат изменения неизвестен. Проверьте файл перед повторным действием.',
    PARTIAL_FAILURE: 'Изменение выполнено частично. Проверьте файлы перед повторным действием.',
    CONFLICT: 'Файл изменился. Обновите сведения и повторите действие.',
    NOT_FOUND: 'Файл или папка больше не найдены.',
    TIMEOUT: 'Не удалось дождаться ответа. Повторите действие.',
    DEVICE_UNAVAILABLE: 'Устройство недоступно. Проверьте подключение и повторите действие.',
  };

  return messages[code] ?? 'Не удалось выполнить действие. Попробуйте ещё раз.';
}
